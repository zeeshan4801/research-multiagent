from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    PageBreak
)

from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

from reportlab.lib.pagesizes import A4

from reportlab.lib.enums import TA_CENTER

from reportlab.pdfbase import pdfmetrics

from reportlab.pdfbase.ttfonts import TTFont

from io import BytesIO

from datetime import datetime

import os



# Register Unicode font

font_path = "DejaVuSans.ttf"


if os.path.exists(font_path):

    pdfmetrics.registerFont(
        TTFont(
            "DejaVu",
            font_path
        )
    )

    FONT = "DejaVu"

else:

    FONT = "Helvetica"





def clean_markdown(text):

    """
    Remove markdown symbols
    """

    replacements = [

        ("**",""),

        ("## ",""),

        ("# ",""),

        ("`","")

    ]


    for old,new in replacements:

        text=text.replace(
            old,
            new
        )


    return text





def add_page_number(canvas, doc):


    canvas.saveState()


    canvas.setFont(
        FONT,
        9
    )


    canvas.drawCentredString(

        A4[0]/2,

        20,

        f"AI Research Report | Page {doc.page}"

    )


    canvas.restoreState()





def create_pdf(content):


    buffer = BytesIO()


    doc = SimpleDocTemplate(

        buffer,

        pagesize=A4,

        rightMargin=60,

        leftMargin=60,

        topMargin=70,

        bottomMargin=50

    )


    styles = getSampleStyleSheet()



    title_style = ParagraphStyle(

        "TitleCustom",

        parent=styles["Title"],

        fontName=FONT,

        fontSize=24,

        alignment=TA_CENTER,

        spaceAfter=20

    )



    heading_style = ParagraphStyle(

        "HeadingCustom",

        parent=styles["Heading2"],

        fontName=FONT,

        fontSize=15,

        spaceBefore=15,

        spaceAfter=10

    )



    body_style = ParagraphStyle(

        "BodyCustom",

        parent=styles["BodyText"],

        fontName=FONT,

        fontSize=10.5,

        leading=16,

        spaceAfter=10

    )



    story=[]



    # Cover Page


    story.append(

        Paragraph(

            "AI Research Report",

            title_style

        )

    )


    story.append(

        Paragraph(

            "Generated by AI Research Multi-Agent System",

            body_style

        )

    )


    story.append(

        Spacer(1,30)

    )


    story.append(

        Paragraph(

            datetime.now().strftime(
                "%B %d, %Y"
            ),

            body_style

        )

    )


    story.append(

        PageBreak()

    )



    content = clean_markdown(content)



    lines = content.split("\n")



    for line in lines:


        line=line.strip()



        if not line:

            continue



        if (

            line.lower().startswith(
                "executive"
            )

            or

            line.lower().startswith(
                "key findings"
            )

            or

            line.lower().startswith(
                "analysis"
            )

            or

            line.lower().startswith(
                "recommendations"
            )

            or

            line.lower().startswith(
                "sources"
            )

        ):


            story.append(

                Paragraph(

                    line,

                    heading_style

                )

            )


        else:


            story.append(

                Paragraph(

                    line,

                    body_style

                )

            )



    doc.build(

        story,

        onFirstPage=add_page_number,

        onLaterPages=add_page_number

    )



    buffer.seek(0)


    return buffer
